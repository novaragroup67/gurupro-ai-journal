// ==============================================================================
// 1. REVIEW STATUS DOMAIN & ENUM
// ==============================================================================

export const PresentationReviewStatusSchema = z.enum([
  "generated",   // Content generated by PPT-1B, waiting for teacher to start review
  "in_review",   // Teacher is actively inspecting slides and verifying content
  "approved",    // Teacher explicitly approved this exact version for pedagogical use
  "rejected",    // Teacher rejected this version with feedback notes
  "superseded",  // Previous version replaced by a newer revision or regenerated content
]);
export type PresentationReviewStatus = z.infer<typeof PresentationReviewStatusSchema>;

// ==============================================================================
// 2. CANONICAL PRESENTATION REVIEW ENTITY SCHEMA
// ==============================================================================

export const PresentationReviewSchema = z.object({
  id: z.string().min(1, "ID review wajib ada."),
  presentationId: z.string().min(1, "Presentation ID wajib ada."),
  contentResultId: z.string().min(1, "Content Result ID wajib ada."),
  generationPlanId: z.string().min(1, "Generation Plan ID wajib ada."),
  moduleId: z.string().min(1, "Module ID wajib ada."),
  approvedVersion: z.number().int().min(1, "Versi rencana wajib >= 1."),
  reviewStatus: PresentationReviewStatusSchema,
  teacherNotes: z.string().max(3000, "Catatan guru maksimal 3000 karakter.").nullable().optional(),
  validationSummary: z.record(z.any()).default({}),
  reviewedBy: z.string().min(1, "ID guru peninjau wajib ada."),
  reviewedAt: z.string().nullable().optional(),
  createdAt: z.string(),
  updatedAt: z.string(),
});
export type PresentationReview = z.infer<typeof PresentationReviewSchema>;

// ==============================================================================
// 3. REVIEW STATE MACHINE & TRANSITIONS
// ==============================================================================

const ALLOWED_PRESENTATION_REVIEW_TRANSITIONS: Record<
  PresentationReviewStatus,
  PresentationReviewStatus[]
> = {
  generated: ["in_review", "approved", "rejected", "superseded"],
  in_review: ["approved", "rejected", "superseded"],
  approved: ["in_review", "superseded"],
  rejected: ["in_review", "superseded"],
  superseded: [], // Terminal state for historical snapshot
};

export function validatePresentationReviewTransition(
  currentStatus: PresentationReviewStatus,
  targetStatus: PresentationReviewStatus
): boolean {
  if (currentStatus === targetStatus) return true;
  const allowed = ALLOWED_PRESENTATION_REVIEW_TRANSITIONS[currentStatus] || [];
  return allowed.includes(targetStatus);
}

export function assertValidPresentationReviewTransition(
  currentStatus: PresentationReviewStatus,
  targetStatus: PresentationReviewStatus
): void {
  if (!validatePresentationReviewTransition(currentStatus, targetStatus)) {
    throw new AiServiceError(
      AI_ERROR_CODES.PRESENTATION_REVIEW_INVALID_TRANSITION,
      `Transisi status review presentasi dari '${currentStatus}' ke '${targetStatus}' tidak diizinkan.`
    );
  }
}

