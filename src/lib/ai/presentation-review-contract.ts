// ==============================================================================
// 5. ILLUSTRATION APPROVAL PRECONDITION VALIDATOR
// ==============================================================================

export interface PresentationIllustrationAuditItem {
  slideId: string;
  slideOrder: number;
  assetId: string;
  isApproved: boolean;
  reviewStatus?: string;
  issue?: string;
}

export interface PresentationIllustrationAuditResult {
  valid: boolean;
  totalReferenced: number;
  approvedCount: number;
  unapprovedCount: number;
  items: PresentationIllustrationAuditItem[];
}

/**
 * Audits all illustration references across slides in a presentation content package.
 * Enforces that every referenced illustration is actively approved for use.
 */
export function auditPresentationIllustrations(
  contentPackage: PresentationContentPackage,
  resolvedIllustrations?: Map<string, ResolvedSlideIllustration>
): PresentationIllustrationAuditResult {
  const items: PresentationIllustrationAuditItem[] = [];
  let unapprovedCount = 0;
  let approvedCount = 0;

  for (const slide of contentPackage.slides) {
    const ref = slide.illustrationReference;
    if (!ref || !ref.assetId) continue;

    const resolved = resolvedIllustrations?.get(slide.slideId);
    if (resolved) {
      approvedCount++;
      items.push({
        slideId: slide.slideId,
        slideOrder: slide.order,
        assetId: ref.assetId,
        isApproved: true,
        reviewStatus: "approved_for_use",
      });
    } else {
      unapprovedCount++;
      const status = ref.reviewStatus || "unreviewed";
      items.push({
        slideId: slide.slideId,
        slideOrder: slide.order,
        assetId: ref.assetId,
        isApproved: false,
        reviewStatus: status,
        issue: `Ilustrasi belum disetujui (status: ${status}).`,
      });
    }
  }

  return {
    valid: unapprovedCount === 0,
    totalReferenced: items.length,
    approvedCount,
    unapprovedCount,
    items,
  };
}
