/**
 * ==============================================================================
 * GURUPRO AI: PRESENTATION TEACHER REVIEW CONTRACT (PPT-1E)
 * ==============================================================================
 *
 * Defines canonical data contracts, Zod schemas, state transition matrices,
 * and input specifications for teacher-driven presentation review & approval.
 *
 * Invariants:
 * 1. Semantic Separation: reviewStatus (generated, in_review, approved, rejected, superseded)
 *    is STRICTLY distinct from artifact generation status and AI content status.
 * 2. Version-Bound Approval: Teacher approval is strictly bound to an exact contentResultId
 *    and approvedVersion. Any modification to content or outline renders previous approval superseded.
 * 3. Human-Only Decision: Review decisions and notes are 100% authored by teachers.
 *    No automated AI approval is permitted.
 * 4. Multi-Tenant RBAC: Only the owning teacher can review and approve a presentation.
 * 5. Illustration Approval Invariant: Presentations referencing illustrations cannot be
 *    approved unless all referenced illustrations have review_status === "approved_for_use".
 */

import { z } from "zod";
